'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {execFileSync}=require('node:child_process');
const py=fs.readFileSync('scripts/prepare-landmark-batch.py','utf8');
const workflow=fs.readFileSync('.github/workflows/remaining-landmark-photo-batch.yml','utf8');
assert.match(workflow,/workflow_dispatch:/);
assert.match(workflow,/contents: read/);
assert.doesNotMatch(workflow,/contents: write|git push|create-pull-request/);
assert.match(py,/PENDING HUMAN REVIEW/);
assert.match(py,/license_short not in/);
assert.match(py,/notPublished.*True/);
assert.match(py,/sourceSha256/);
assert.match(py,/webpSha256/);
assert.doesNotMatch(py,/import-landmark-photo|git push|manifest\.ids\.append/);
const report=JSON.parse(execFileSync(process.execPath,['scripts/release-readiness.cjs'],{encoding:'utf8'}));
assert.equal(report.landmarkTotal,39);
assert.equal(report.realOfflinePhotos+report.remainingLandmarkIds.length,39);
assert.equal(report.manualDeviceAcceptanceVerified,false);
assert.equal(report.manualMediaReviewVerified,false);
assert.equal(report.readyForFinalSignoff,false);
console.log('PASS remaining landmark discovery remains review-only; release gaps accurately reported');
